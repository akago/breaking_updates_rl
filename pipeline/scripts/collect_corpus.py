#!/usr/bin/env python3
"""
collect_corpus.py -- build the `seen` and `unseen` reference corpora.

    unseen : Java files whose FIRST commit is after the release date of every
             model you evaluate. Provably outside pre-training, and the
             argument rests on release dates, not on the vendors' undisclosed
             cut-offs.
    seen   : Java files from well-known pre-2022 repositories that have not
             been touched since. Their exact current content is what any code
             corpus of that era captured.

Both modes clone repos with git and read history; nothing but git + the GitHub
search API is required.

    export GITHUB_TOKENS=ghp_aaa,ghp_bbb,ghp_ccc   # comma-separated, rotates
                                                    # to the next one on a 403
    # or a single token, either name works:
    export GITHUB_TOKEN=ghp_...

    # 1) unseen -- repos created after your latest model release
    python collect_corpus.py unseen --after 2026-07-01 --n 150 \
        --out data/unseen.jsonl

    # 2) seen -- curated pre-2022 projects, files frozen before 2022
    python collect_corpus.py seen --before 2022-01-01 --n 150 \
        --out data/seen.jsonl

    # 3) match both to your BUMP files on token length before scoring
    python collect_corpus.py match --bump data/bump_files.jsonl \
        --pools data/seen.jsonl data/unseen.jsonl --out-dir data/matched

Output rows are exactly what mink_score.py expects:
    {"id": "owner/repo:path", "group": "seen|unseen", "text": "...",
     "n_lines": 120, "first_commit": "2026-07-14", "repo_created": "..."}
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import random
import re
import subprocess
import sys
import tempfile
import urllib.error
import urllib.parse
import urllib.request

GH = "https://api.github.com"

# Pre-2022, ubiquitous, mirrored everywhere -- the safest possible `seen` set.
SEEN_REPOS = [
    "apache/commons-lang", "apache/commons-io", "apache/commons-collections",
    "apache/commons-codec", "apache/commons-cli", "apache/commons-text",
    "google/guava", "google/gson", "junit-team/junit4", "mockito/mockito",
    "FasterXML/jackson-databind", "FasterXML/jackson-core", "square/okhttp",
    "square/retrofit", "netty/netty", "ReactiveX/RxJava", "qos-ch/slf4j",
    "spring-projects/spring-framework", "apache/dubbo", "alibaba/fastjson",
]

GENERATED = re.compile(
    r"@Generated|Generated by the protocol buffer|DO NOT EDIT|"
    r"This file was automatically generated|autogenerated", re.I)
IMPORT = re.compile(r"^\s*import\s+(?:static\s+)?([\w.]+)", re.M)
TEST_LIBS = ("org.junit", "junit.", "org.mockito", "org.hamcrest",
             "org.assertj", "org.testng", "org.easymock")
TEST_PATH = re.compile(r"(^|/)(test|tests|androidTest)/|Test\.java$|Tests\.java$|"
                       r"IT\.java$", re.I)
LICENSE_HEAD = re.compile(r"\A\s*(?:/\*.*?\*/\s*|(?://[^\n]*\n\s*)+)", re.S)


# --------------------------------------------------------------------------- #
def _load_tokens() -> list[str]:
    """GITHUB_TOKENS (comma-separated, matches .env in this repo) takes
    priority; GITHUB_TOKEN1/GITHUB_TOKEN2/GITHUB_TOKEN are accepted too so a
    single-token setup keeps working."""
    multi = os.environ.get("GITHUB_TOKENS", "")
    tokens = [t.strip() for t in multi.split(",") if t.strip()]
    if tokens:
        return tokens
    for name in ("GITHUB_TOKEN1", "GITHUB_TOKEN2", "GITHUB_TOKEN"):
        t = os.environ.get(name)
        if t:
            tokens.append(t)
    return tokens


TOKENS = _load_tokens()
_token_idx = 0


def _request(path: str):
    """GET path, rotating to the next token on 401/403 so one bad or exhausted
    token doesn't stop the run. Returns (json_body, response_headers) -- the
    headers are needed by commit_count() below, which api() callers don't."""
    global _token_idx
    attempts = max(1, len(TOKENS))
    last_err = None
    for _ in range(attempts):
        req = urllib.request.Request(GH + path,
                                     headers={"Accept": "application/vnd.github+json",
                                              "User-Agent": "memprobe"})
        if TOKENS:
            req.add_header("Authorization", f"Bearer {TOKENS[_token_idx]}")
        try:
            with urllib.request.urlopen(req, timeout=60) as r:
                return json.load(r), r.headers
        except urllib.error.HTTPError as e:
            last_err = e
            if e.code in (401, 403) and len(TOKENS) > 1:
                reason = "rate limit" if e.code == 403 else "invalid/expired token"
                _token_idx = (_token_idx + 1) % len(TOKENS)
                print(f"  {e.code} ({reason}) -- rotating to token {_token_idx + 1}/{len(TOKENS)}",
                      file=sys.stderr)
                continue
            raise
    raise last_err


def api(path: str) -> dict:
    body, _ = _request(path)
    return body


def commit_count(full_name: str) -> int:
    """Total commits on the default branch. GitHub has no direct field for
    this -- the standard trick is to ask for 1 commit per page and read the
    last page number back off the response's Link header."""
    _, headers = _request(f"/repos/{full_name}/commits?per_page=1")
    m = re.search(r'[?&]page=(\d+)>;\s*rel="last"', headers.get("Link", ""))
    return int(m.group(1)) if m else 1


def git(args, cwd=None) -> str:
    return subprocess.run(["git"] + args, cwd=cwd, capture_output=True,
                          text=True, timeout=600).stdout.strip()


def third_party_imports(src: str, pkg: str | None) -> int:
    """BUMP files are CLIENT code: they import third-party libraries. Matching
    on this keeps the corpora comparable in kind, not just in language.
    Test frameworks do not count -- otherwise the filter selects unit tests,
    which look nothing like the client code you evaluate on."""
    n = 0
    for imp in IMPORT.findall(src):
        if imp.startswith(("java.", "javax.", "jakarta.")):
            continue
        if imp.startswith(TEST_LIBS):
            continue
        if pkg and imp.startswith(pkg.rsplit(".", 1)[0]):
            continue
        n += 1
    return n


def strip_license(src: str) -> str:
    """The paper scores file content without license headers; boilerplate that
    appears in thousands of repos is trivially 'memorised' by every model and
    only adds noise to the score."""
    return LICENSE_HEAD.sub("", src, count=1).lstrip("\n")


def keep(src: str, min_lines: int, min_imports: int,
         rel: str = "", exclude_tests: bool = True) -> bool:
    if exclude_tests and rel and TEST_PATH.search(rel):
        return False
    if len(src.splitlines()) < min_lines:
        return False
    if GENERATED.search(src[:4000]):
        return False
    m = re.search(r"^\s*package\s+([\w.]+)", src, re.M)
    return third_party_imports(src, m.group(1) if m else None) >= min_imports


def emit(rows, out):
    seen_hashes, kept = set(), []
    for r in rows:
        h = hashlib.sha256(re.sub(r"\s+", "", r["text"]).encode()).hexdigest()
        if h in seen_hashes:
            continue
        seen_hashes.add(h)
        kept.append(r)
    os.makedirs(os.path.dirname(out) or ".", exist_ok=True)
    with open(out, "w") as f:
        for r in kept:
            f.write(json.dumps(r) + "\n")
    print(f"wrote {out}: {len(kept)} files "
          f"({len(rows)-len(kept)} exact/whitespace duplicates dropped)")


# --------------------------------------------------------------------------- #
def cmd_unseen(a):
    q = urllib.parse.quote(
        f"language:Java created:>{a.after} stars:>={a.min_stars} "
        f"fork:false archived:false")
    repos, page = [], 1
    while len(repos) < a.repos and page <= 10:
        r = api(f"/search/repositories?q={q}&sort=updated&per_page=100&page={page}")
        items = r.get("items", [])
        if not items:
            break
        repos += items
        page += 1
    print(f"{len(repos)} candidate repos created after {a.after}")

    rows = []
    with tempfile.TemporaryDirectory() as tmp:
        for repo in repos:
            if len(rows) >= a.n:
                break
            full, created = repo["full_name"], repo["created_at"][:10]
            if created < a.after:
                continue
            if a.min_commits > 0:
                try:
                    if commit_count(full) < a.min_commits:
                        continue
                except (urllib.error.HTTPError, urllib.error.URLError):
                    continue
            d = os.path.join(tmp, full.replace("/", "_"))
            if subprocess.run(["git", "clone", "--quiet", repo["clone_url"], d],
                              capture_output=True, timeout=600).returncode:
                continue
            files = [f for f in git(["ls-files", "*.java"], d).split("\n") if f]
            random.Random(0).shuffle(files)
            n_repo = 0
            for rel in files:
                if len(rows) >= a.n or n_repo >= a.per_repo:
                    break
                # date the file was ADDED 
                hist = git(["log", "--diff-filter=A", "--format=%aI", "--", rel], d)
                if not hist:
                    continue
                first = hist.split("\n")[-1][:10]
                if first < a.after:
                    continue
                try:
                    src = open(os.path.join(d, rel), encoding="utf-8",
                               errors="ignore").read()
                except OSError:
                    continue
                if not a.keep_header:
                    src = strip_license(src)      # strip BEFORE filtering, so
                # min-lines applies to the content that actually gets scored
                if not keep(src, a.min_lines, a.min_imports, rel,
                            not a.include_tests):
                    continue
                rows.append({"id": f"{full}:{rel}", "group": "unseen",
                             "text": src, "n_lines": len(src.splitlines()),
                             "first_commit": first, "repo_created": created})
                n_repo += 1
            print(f"  {full}: +{n_repo}  (total {len(rows)})", flush=True)
    emit(rows, a.out)


def cmd_seen(a):
    repos = a.repos.split(",") if a.repos else SEEN_REPOS
    rows = []
    with tempfile.TemporaryDirectory() as tmp:
        for full in repos:
            if len(rows) >= a.n:
                break
            d = os.path.join(tmp, full.replace("/", "_"))
            if subprocess.run(
                    ["git", "clone", "--quiet",
                     f"https://github.com/{full}.git", d],
                    capture_output=True, timeout=1800).returncode:
                print(f"  clone failed: {full}")
                continue
            rev = git(["rev-list", "-1", f"--before={a.before}", "HEAD"], d)
            if not rev:
                print(f"  no pre-{a.before} commit: {full}")
                continue
            git(["checkout", "--quiet", rev], d)
            asof = git(["log", "-1", "--format=%aI"], d)[:10]

            files = [f for f in git(["ls-files", "*.java"], d).split("\n") if f]
            random.Random(0).shuffle(files)
            n_repo = 0
            for rel in files:
                if len(rows) >= a.n or n_repo >= a.per_repo:
                    break
                last = asof
                try:
                    src = open(os.path.join(d, rel), encoding="utf-8",
                               errors="ignore").read()
                except OSError:
                    continue
                if not a.keep_header:
                    src = strip_license(src)      # strip BEFORE filtering, so
                # min-lines applies to the content that actually gets scored
                if not keep(src, a.min_lines, a.min_imports, rel,
                            not a.include_tests):
                    continue
                rows.append({"id": f"{full}:{rel}", "group": "seen",
                             "text": src, "n_lines": len(src.splitlines()),
                             "last_commit": last})
                n_repo += 1
            print(f"  {full}: +{n_repo}  (total {len(rows)})", flush=True)
    emit(rows, a.out)


def cmd_match(a):
    """Down-sample each pool so its length distribution matches the BUMP files.
    Without this, AUC measures file length, not membership."""
    import numpy as np

    def load(p):
        return [json.loads(l) for l in open(p) if l.strip()]

    bump = load(a.bump)
    blen = np.array([len(x["text"].splitlines()) for x in bump])
    edges = np.unique(np.quantile(blen, np.linspace(0, 1, a.bins + 1)))
    want = [int(((blen >= lo) & (blen <= hi)).sum()) for lo, hi in
            zip(edges[:-1], edges[1:])]
    scale = a.n / max(1, sum(want))
    want = [max(1, int(round(w * scale))) for w in want]

    os.makedirs(a.out_dir, exist_ok=True)
    for p in a.pools:
        pool = load(p)
        rng = random.Random(0)
        rng.shuffle(pool)
        out, short = [], 0
        for (lo, hi), w in zip(zip(edges[:-1], edges[1:]), want):
            bucket = [x for x in pool
                      if lo <= len(x["text"].splitlines()) <= hi]
            if len(bucket) < w:
                short += w - len(bucket)
            out += bucket[:w]
        dst = os.path.join(a.out_dir, os.path.basename(p))
        with open(dst, "w") as f:
            for r in out:
                f.write(json.dumps(r) + "\n")
        msg = f"  {dst}: {len(out)} files"
        if short:
            msg += f"  (WARNING: {short} short of target -- collect more)"
        print(msg)


# --------------------------------------------------------------------------- #
def main():
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)

    def common(p):
        p.add_argument("--n", type=int, default=150)
        p.add_argument("--per-repo", type=int, default=8,
                       help="cap per repo so one project cannot dominate")
        p.add_argument("--min-lines", type=int, default=30)
        p.add_argument("--min-imports", type=int, default=1,
                       help="third-party imports required (client-code filter)")
        p.add_argument("--include-tests", action="store_true",
                       help="by default unit tests are excluded")
        p.add_argument("--keep-header", action="store_true",
                       help="by default the leading license header is stripped")
        p.add_argument("--out", required=True)

    u = sub.add_parser("unseen"); common(u)
    u.add_argument("--after", required=True,
                   help="YYYY-MM-DD, >= the LATEST model release date")
    u.add_argument("--repos", type=int, default=200)
    u.add_argument("--min-stars", type=int, default=10)
    u.add_argument("--min-commits", type=int, default=100,
                   help="skip repos with fewer total commits. ")

    s = sub.add_parser("seen"); common(s)
    s.add_argument("--before", default="2022-01-01")
    s.add_argument("--repos", default="", help="comma-separated owner/name")

    m = sub.add_parser("match")
    m.add_argument("--bump", required=True)
    m.add_argument("--pools", nargs="+", required=True)
    m.add_argument("--out-dir", default="data/matched")
    m.add_argument("--n", type=int, default=150)
    m.add_argument("--bins", type=int, default=6)

    a = ap.parse_args()
    if a.cmd == "unseen":
        if not TOKENS:
            sys.exit("set GITHUB_TOKENS (or GITHUB_TOKEN1/2/GITHUB_TOKEN) -- "
                      "the search API is rate-limited without it")
        cmd_unseen(a)
    elif a.cmd == "seen":
        cmd_seen(a)
    else:
        cmd_match(a)


if __name__ == "__main__":
    main()
